#!/bin/sh
set -e

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

PORT=${PORT:-8080}
URL=${URL:-http://127.0.0.1:$PORT}
DURATION=${DURATION:-30s}
THREADS=${THREADS:-4}
CONNECTIONS=${CONNECTIONS:-100}
RESULTS=benchmarks/results/http.md

mkdir -p benchmarks/results

cargo build --quiet --release

cargo build --quiet --release
KHIPU=./target/release/khipu

rustc -O benchmarks/http/server.rs -o benchmarks/http/server_rs
go build -o benchmarks/http/server_go benchmarks/http/server.go 2>/dev/null || true

STARTED=""
cleanup() { [ -n "$STARTED" ] && kill "$STARTED" 2>/dev/null || true; }
trap cleanup EXIT

wait_up() {
    for _ in $(seq 1 100); do
        if curl -fsS "$URL/hello" >/dev/null 2>&1; then return 0; fi
        sleep 0.05
    done
    echo "server did not start" >&2
    exit 1
}

measure() {
    name="$1"
    shift
    "$@" >/dev/null 2>&1 &
    STARTED=$!
    wait_up
    hello=$(wrk -t"$THREADS" -c"$CONNECTIONS" -d"$DURATION" "$URL/hello" | awk '/Requests\/sec/ {print $2}')
    json=$(wrk -t"$THREADS" -c"$CONNECTIONS" -d"$DURATION" "$URL/json" | awk '/Requests\/sec/ {print $2}')
    file=$(wrk -t"$THREADS" -c"$CONNECTIONS" -d"$DURATION" "$URL/file" | awk '/Requests\/sec/ {print $2}')
    kill "$STARTED" 2>/dev/null || true
    wait "$STARTED" 2>/dev/null || true
    STARTED=""
    printf '%s %s %s %s\n' "$name" "$hello" "$json" "$file"
}

: > "$RESULTS.measure"

measure khipu "$KHIPU" benchmarks/http/server.kp >> "$RESULTS.measure"
measure node node benchmarks/http/node.mjs >> "$RESULTS.measure"
measure go benchmarks/http/server_go >> "$RESULTS.measure"
measure rust-std benchmarks/http/server_rs >> "$RESULTS.measure"

{
    echo ""
    echo "## HTTP"
    echo ""
    echo "Khipu, Node (built-in \`http\`), Go (\`net/http\`) and Rust (\`std\` only, one thread per connection),"
    echo "same three routes (\`/hello\`, \`/json\`, \`/file\`), same box, same \`wrk\` command:"
    echo "\`wrk -t$THREADS -c$CONNECTIONS -d$DURATION URL/ROUTE\`. Requests/sec. Node kept alive; others \`connection: close\`."
    echo "Generated by \`scripts/bench-http.sh\`, not edited by hand."
    echo ""
    echo "| server | /hello | /json | /file |"
    echo "|---|---|---|---|"
    while read -r name hello json file; do
        echo "| $name | $hello | $json | $file |"
    done < "$RESULTS.measure"
rm -f "$RESULTS.measure"
} > "$RESULTS"

python3 - "$RESULTS" <<'PY'
import sys
path = "BENCHMARKS.md"
section = open(sys.argv[1]).read()
text = open(path).read()
marker = "\n## HTTP\n"
if marker in text:
    text = text.split(marker)[0].rstrip() + "\n" + section
else:
    text = text.rstrip() + "\n" + section
open(path, "w").write(text)
PY

cat "$RESULTS"
